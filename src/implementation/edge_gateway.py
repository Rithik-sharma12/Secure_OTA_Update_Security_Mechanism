@app.post('/api/deployments')
def create_deployment(payload: DeploymentCreatePayload, _auth: None = Depends(require_write_auth)) -> dict[str, Any]:
    with STATE_LOCK:
        releases = STATE.get('releases', [])
        if not releases:
            raise HTTPException(status_code=404, detail='No releases available for deployment.')

        selected_release = releases[0]
        if payload.releaseId:
            match = next((release for release in releases if release.get('id') == payload.releaseId), None)
            if not match:
                raise HTTPException(status_code=404, detail=f'Release {payload.releaseId} not found.')
            selected_release = match

        release_id = str(selected_release.get('id'))
        if payload.deviceIds:
            target_device_ids = [str(device_id) for device_id in payload.deviceIds]
        else:
            target_device_ids = list(STATE.get('devices', {}).keys())

        if not target_device_ids:
            raise HTTPException(status_code=400, detail='No target devices available for deployment.')

        success_count = 0
        failure_count = 0
        logs: list[str] = []
        now_iso = utc_now_iso()

        for device_id in target_device_ids:
            device = STATE['devices'].get(device_id)
            if not device:
                failure_count += 1
                logs.append(f'Device {device_id}: not found on gateway.')
                continue

            ash_score = safe_int(device.get('ash', 0), 0)
            if ash_score <= 40:
                failure_count += 1
                device['status'] = 'Quarantined'
                logs.append(f'Device {device_id}: blocked due to ASH={ash_score} quarantine threshold.')
                push_event_locked(
                    event_type='security',
                    severity='error',
                    title='Deployment Blocked by ASH Policy',
                    description=f'Device {device_id} failed deployment due to low ASH score ({ash_score}).',
                    device_id=device_id,
                )
                continue

            success_count += 1
            device['fw'] = str(selected_release.get('version', device.get('fw', '0.0.0')))
            device['status'] = 'Healthy'
            device['last_seen'] = now_iso
            logs.append(f"Device {device_id}: updated to v{device['fw']} successfully.")
            push_event_locked(
                event_type='firmware_update',
                severity='success',
                title='Device Updated',
                description=f"Device {device_id} updated to firmware v{device['fw']}.",
                device_id=device_id,
            )

        deployment_status = 'success'
        if success_count > 0 and failure_count > 0:
            deployment_status = 'partial'
        elif success_count == 0:
            deployment_status = 'failed'

        deployment = {
            'id': f"deployment-{uuid.uuid4().hex[:10]}",
            'releaseId': release_id,
            'deviceIds': target_device_ids,
            'status': deployment_status,
            'startedAt': now_iso,
            'completedAt': utc_now_iso(),
            'successCount': success_count,
            'failureCount': failure_count,
            'logs': '\n'.join(logs),
        }

        STATE['deployments'].insert(0, deployment)
        STATE['deployments'] = STATE['deployments'][:MAX_RELEASES]
        STATE['updatedAt'] = utc_now_iso()

        if failure_count > 0:
            push_alert_locked(
                f"Deployment {deployment['id']} completed with failures ({failure_count} failed / {success_count} succeeded)."
            )

        push_event_locked(
            event_type='deployment',
            severity='success' if failure_count == 0 else 'warning',
            title='Deployment Completed',
            description=f"Release {release_id} deployed with status={deployment_status}.",
        )

        persist_state_locked()

    return {'ok': True, 'deployment': deployment}



#!/usr/bin/env python3
"""
Regenerate esp32_ota_main/ca_bundle.h: the root certificates an https://
gateway behind Cloudflare can chain to, as one PEM bundle the ESP32 trusts.

Cloudflare's edge certificates (Universal SSL, and the tunnel hostnames) are
issued by Let's Encrypt, Google Trust Services or SSL.com, and Cloudflare
switches between them without notice. A board that pinned only today's root
would stop updating the day the issuer changes, and the fix needs a USB
reflash. Trusting these few public roots keeps verification strict (only
these CAs, hostname checked) while surviving the rotation.

    python firmware/tools/make_ca_bundle.py

Roots are read from the Mozilla store shipped with certifi
(pip install certifi). Override with an explicit OTA_ROOT_CA in ota_config.h
to pin a single root instead.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOTS = [
    # Let's Encrypt
    "ISRG Root X1",
    "ISRG Root X2",
    # Google Trust Services (GTS Root R1 is also cross-signed by GlobalSign Root CA)
    "GTS Root R1",
    "GTS Root R2",
    "GTS Root R3",
    "GTS Root R4",
    "GlobalSign Root CA",
    # SSL.com
    "SSL.com Root Certification Authority RSA",
    "SSL.com Root Certification Authority ECC",
    "SSL.com TLS RSA Root CA 2022",
    "SSL.com TLS ECC Root CA 2022",
    # DigiCert (older Cloudflare certificates, Advanced Certificate Manager)
    "DigiCert Global Root CA",
    "DigiCert Global Root G2",
]

OUT = Path(__file__).resolve().parents[1] / "esp32_ota_main" / "ca_bundle.h"


def main() -> None:
    try:
        import certifi
        from cryptography import x509
        from cryptography.x509.oid import NameOID
    except ImportError:
        sys.exit("pip install certifi cryptography")

    pem = Path(certifi.where()).read_text(encoding="ascii")
    blocks = [b + "-----END CERTIFICATE-----\n" for b in pem.split("-----END CERTIFICATE-----") if "BEGIN" in b]
    found: dict[str, str] = {}
    for block in blocks:
        body = block[block.index("-----BEGIN CERTIFICATE-----"):]
        cert = x509.load_pem_x509_certificate(body.encode())
        names = cert.subject.get_attributes_for_oid(NameOID.COMMON_NAME)
        cn = names[0].value if names else ""
        if cn in ROOTS and cn not in found:
            found[cn] = body
    missing = [name for name in ROOTS if name not in found]
    if missing:
        print("Not in this certifi store (skipped):", ", ".join(missing))

    lines = [
        "// Generated by firmware/tools/make_ca_bundle.py. Do not edit by hand.",
        "// Public root certificates (no secrets) for https:// gateways behind",
        "// Cloudflare: " + ", ".join(found) + ".",
        "#pragma once",
        "",
        "static const char OTA_DEFAULT_CA_BUNDLE[] PROGMEM =",
    ]
    for cn, body in found.items():
        lines.append(f"  // {cn}")
        for row in body.strip().splitlines():
            lines.append(f'  "{row}\\n"')
    lines[-1] = lines[-1] + ";"
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Wrote {OUT} with {len(found)} roots.")


if __name__ == "__main__":
    main()

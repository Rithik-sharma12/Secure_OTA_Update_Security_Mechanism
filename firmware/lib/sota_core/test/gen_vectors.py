"""Write test/vectors.h: Ed25519 manifest signatures made exactly as the gateway makes them.

Run:  python3 gen_vectors.py   (needs the `cryptography` package)
The statement format must match apps/gateway/gateway/crypto.py manifest_signing_message().
"""
import base64
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

SEED = bytes(range(32))  # fixed test key; never used outside this test
key = Ed25519PrivateKey.from_private_bytes(SEED)
pub = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw).hex()


def message(version, sha256, image_sha256, size):
    return '\n'.join(['SOTA-MANIFEST-V1', version, sha256, image_sha256, str(size)]).encode()


cases = [
    ('2.5.1', 'a' * 64, 'b' * 64, 1004384),
    ('1.0.0', '0123456789abcdef' * 4, '', 14200),
]
lines = [f'#define TEST_PUBLIC_KEY "{pub}"']
for i, (v, s, img, size) in enumerate(cases):
    sig = base64.b64encode(key.sign(message(v, s, img, size))).decode()
    lines += [
        f'#define TEST{i}_VERSION "{v}"',
        f'#define TEST{i}_SHA256 "{s}"',
        f'#define TEST{i}_IMAGE "{img}"',
        f'#define TEST{i}_SIZE {size}UL',
        f'#define TEST{i}_SIG "{sig}"',
        f'#define TEST{i}_MESSAGE "{message(v, s, img, size).decode().encode("unicode_escape").decode()}"',
    ]
import hashlib
data = bytes((i * 7 + 3) & 0xFF for i in range(1000))
lines += [f'#define TEST_SHA256_1000 "{hashlib.sha256(data).hexdigest()}"',
          f'#define TEST_SHA256_55 "{hashlib.sha256(data[:55]).hexdigest()}"',
          f'#define TEST_SHA256_64 "{hashlib.sha256(data[:64]).hexdigest()}"']
Path(__file__).with_name('vectors.h').write_text('/* Generated by gen_vectors.py */\n' + '\n'.join(lines) + '\n')
print('wrote vectors.h')

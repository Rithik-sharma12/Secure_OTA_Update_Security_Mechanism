router = APIRouter()

# ESP32 images are ~1-2 MB; 32 MB is a generous ceiling that still bounds the
# amount a single request can buffer in memory.
MAX_UPLOAD_BYTES = 32 * 1024 * 1024


# Real API key guard, imported directly so Depends() captures the actual
# function (see gateway/auth.py for why this must not be monkey-patched).
_require_write_auth = require_write_auth


@router.get('/api/releases')
def list_releases(_read: None = Depends(require_read_auth)) -> dict[str, Any]:
    snapshot = gateway_snapshot()
    return {'ok': True, 'releases': snapshot.get('releases', [])}


@router.post('/api/releases')
def create_release(payload: ReleaseCreatePayload, request: Request, _auth: None = Depends(_require_write_auth)) -> dict[str, Any]:
    compatibility = normalize_compatibility(payload.compatible)

    try:
        with STATE_LOCK:
            release, manifest, pipeline = create_release_locked(
                version=payload.version,
                description=payload.description.strip() or 'Firmware release generated by OTA gateway.',
                changelog=payload.changelog.strip() or 'Security and reliability updates.',
                compatible=compatibility,
                source_file_path=payload.sourceFilePath,
                status='published',
                image_sha256=payload.imageSha256,
                secure_package=payload.securePackage,
            )
            STATE['updatedAt'] = utc_now_iso()
            persist_state_locked()
    except ValueError as error:
        message = str(error)
        status_code = 409 if 'already exists' in message.lower() else 400
        raise HTTPException(status_code=status_code, detail=message) from error

    audit_note(request, 'release.published', f"v{release.get('version')} for {', '.join(release.get('compatible', [])) or 'all'}")
    return {'ok': True, 'release': release, 'manifest': manifest, 'pipeline': pipeline}


@router.post('/api/releases/upload')
async def upload_release(
    request: Request,
    file: UploadFile = File(..., description='Compiled firmware .bin'),
    version: str = Form(...),
    description: str = Form('Firmware release uploaded from the OTA dashboard.'),
    changelog: str = Form('Security and reliability updates.'),
    compatible: str = Form(''),
    imageSha256: str = Form('', description='SHA-256 of the plaintext image, for secure packages'),
    securePackage: bool | None = Form(None, description='Artifact is an encrypted package'),
    factoryImage: UploadFile | None = File(
        None, description='Optional merged first-flash image (bootloader + partitions + app) written at 0x0'
    ),
    _auth: None = Depends(_require_write_auth),
) -> dict[str, Any]:
    """Publish a release directly from an uploaded firmware binary.

    This is the web-UI publish path: the browser sends the .bin as multipart
    form data, so no file has to pre-exist on the gateway's filesystem (which
    is unreachable from the browser, and is a separate container in Docker).
    """
    original_name = (file.filename or '').strip()
    if not original_name.lower().endswith('.bin'):
        raise HTTPException(status_code=400, detail='Firmware artifact must be a .bin file.')

    payload = await file.read()
    if not payload:
        raise HTTPException(status_code=400, detail='Uploaded firmware artifact is empty.')

    if len(payload) > MAX_UPLOAD_BYTES:
        raise HTTPException(
            status_code=413,
            detail=f'Firmware exceeds the {MAX_UPLOAD_BYTES // (1024 * 1024)} MB upload limit.',
        )

    factory_payload: bytes | None = None
    if factoryImage is not None and (factoryImage.filename or '').strip():
        factory_payload = await factoryImage.read()
        if not factory_payload:
            raise HTTPException(status_code=400, detail='Uploaded factory image is empty.')
        if len(factory_payload) > MAX_UPLOAD_BYTES:
            raise HTTPException(status_code=413, detail='Factory image exceeds the upload limit.')

    requested = [entry.strip() for entry in compatible.split(',') if entry.strip()]
    compatibility = normalize_compatibility(requested or None)

    try:
        with STATE_LOCK:
            release, manifest, pipeline = create_release_locked(
                version=version,
                description=description.strip() or 'Firmware release uploaded from the OTA dashboard.',
                changelog=changelog.strip() or 'Security and reliability updates.',
                compatible=compatibility,
                status='published',
                artifact_bytes=payload,
                artifact_label=f'upload:{original_name}',
                image_sha256=imageSha256 or None,
                secure_package=securePackage,
                factory_bytes=factory_payload,
            )
            STATE['updatedAt'] = utc_now_iso()
            persist_state_locked()
    except ValueError as error:
        message = str(error)
        status_code = 409 if 'already exists' in message.lower() else 400
        raise HTTPException(status_code=status_code, detail=message) from error

    audit_note(request, 'release.published', f"v{release.get('version')} for {', '.join(release.get('compatible', [])) or 'all'}")
    return {'ok': True, 'release': release, 'manifest': manifest, 'pipeline': pipeline}


@router.get('/api/releases/latest')
def latest_release(_read: None = Depends(require_read_auth)) -> dict[str, Any]:
    snapshot = gateway_snapshot()
    releases = snapshot.get('releases', [])
    if not releases:
        raise HTTPException(status_code=404, detail='No release available.')

    return {'ok': True, 'release': releases[0], 'manifest': snapshot.get('manifest')}


@router.get('/api/releases/factory')
def download_factory_image(
    device_type: str = Query(default='ESP32'),
    _read: None = Depends(require_read_auth),
) -> Any:
    """Merged first-flash image for a blank board, written over USB at 0x0.

    Operator-only (the gateway key, never a device token): it is plain
    firmware, and a secure release exists so the image is not handed out in
    the clear. Not referenced by any device manifest. Returns the newest
    published release for `device_type` that has one, which may be older than
    the newest release; the board then updates over the air.
    """
    resolved_type = normalize_device_type(device_type)
    with STATE_LOCK:
        release = latest_factory_release_locked(resolved_type)
        newest = latest_release_for_device_locked(resolved_type)
        factory = dict(release.get('factoryImage') or {}) if release else {}
        version = str(release.get('version', '')) if release else ''
    if not release or not factory.get('name'):
        raise HTTPException(
            status_code=404,
            detail={
                'message': (
                    f'No published {resolved_type} release has a factory image. Publish one with the '
                    'merged firmware-full.bin (scripts/go-online.sh build, or the release workflow).'
                ),
                'deviceType': resolved_type,
            },
        )

    path = (FIRMWARE_CACHE_DIR / str(factory['name'])).resolve()
    if path.parent != FIRMWARE_CACHE_DIR or not path.is_file():
        raise HTTPException(status_code=503, detail=f'Factory image for v{version} is missing from the gateway cache.')

    return FileResponse(
        path=path,
        media_type='application/octet-stream',
        filename=str(factory['name']),
        headers={
            'Cache-Control': 'no-store',
            'X-Firmware-Version': version,
            'X-Firmware-Sha256': str(factory.get('sha256', '')),
            'X-Firmware-Filename': str(factory['name']),
            'X-Latest-Version': str(newest.get('version', '')) if newest else version,
        },
    )


@router.get('/releases/latest/manifest')
def get_manifest(
    device_id: str | None = Query(default=None),
    device_type: str | None = Query(default=None),
    _read: None = Depends(require_device_read_auth),
) -> Any:
    """Manifest for the caller.

    With `device_type` (or a `device_id` the gateway already knows), returns
    the newest release whose `compatible` list covers that architecture. This
    is what stops an ESP8266 being handed an ESP32 image — `compatible` was
    previously recorded on every release and never read.

    With no identifying parameter the global latest manifest is returned, so
    firmware built before this existed keeps working unchanged.
    """
    resolved_type = ''
    known_device: dict[str, Any] | None = None
    if device_id:
        with STATE_LOCK:
            found = STATE.get('devices', {}).get(str(device_id))
            known_device = dict(found) if found else None
    if device_type:
        resolved_type = normalize_device_type(device_type)
    elif known_device:
        resolved_type = str(known_device.get('arch', ''))

    if resolved_type:
        with STATE_LOCK:
            if device_id:
                # Per-device answer: a dashboard deployment assigned to this
                # board wins over "newest compatible" (see release_for_device_locked).
                release = release_for_device_locked(str(device_id), resolved_type)
                if release is None and known_device is not None:
                    # Auto-update is off and nothing is assigned: tell the
                    # device it is current rather than failing its poll, which
                    # the firmware would count against its health score.
                    return {
                        'version': str(known_device.get('fw', '0.0.0')),
                        'updateAvailable': False,
                        'reason': 'No deployment is assigned to this device.',
                    }
            else:
                release = latest_release_for_device_locked(resolved_type)
            manifest = _manifest_for_release_locked(release) if release else None
            published_types = published_device_types_locked()

        # A release record with no manifest means the record survived but its
        # cached binary did not, so nothing can be signed over real bytes. That
        # is a gateway fault, not "nothing published" — keep the two apart so
        # the dashboard does not tell the operator to publish a release that
        # already exists.
        if release and not manifest:
            raise HTTPException(
                status_code=503,
                detail={
                    'message': (
                        f'Release {release.get("version", "unknown")} targets {resolved_type}, but its '
                        'firmware binary is missing from the gateway cache. Re-publish the release.'
                    ),
                    'deviceType': resolved_type,
                    'version': str(release.get('version', '')),
                    'publishedDeviceTypes': published_types,
                },
            )

        if not manifest:
            raise HTTPException(
                status_code=404,
                detail={
                    'message': f'No release available for device type {resolved_type}.',
                    'deviceType': resolved_type,
                    'publishedDeviceTypes': published_types,
                },
            )
        return manifest

    # Unidentified caller — legacy global behaviour.
    if MANIFEST_FILE.exists():
        return FileResponse(path=MANIFEST_FILE, media_type='application/json')

    snapshot = gateway_snapshot()
    manifest = snapshot.get('manifest')
    if not manifest:
        raise HTTPException(status_code=404, detail='No manifest available.')

    with open(MANIFEST_FILE, 'w', encoding='utf-8') as file:
        json.dump(manifest, file, indent=2)
    return manifest


@router.get('/releases/latest/public-key')
def get_public_signing_key() -> dict[str, Any]:
    public_key_pem = get_signing_key().public_key().public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    ).decode('utf-8')

    return {
        'algorithm': SIGNING_ALGORITHM,
        'keyId': SIGNING_KEY_ID,
        'fingerprint': signing_fingerprint_hex(),
        'publicKeyPem': public_key_pem,
    }
